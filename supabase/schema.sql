create or replace function public.current_company_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
    select company_id
    from public.profiles
    where id = auth.uid()
      and active = true
    limit 1
$$;

create or replace function public.current_profile_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(permission in ('diretor', 'admin', 'owner'), false)
    from public.profiles
    where id = auth.uid()
      and active = true
    limit 1
$$;

create or replace function public.current_company_plan_slug()
returns text
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(plan_slug, plan, 'starter')
    from public.companies
    where id = public.current_company_id()
    limit 1
$$;

create or replace function public.current_company_subscription_status()
returns text
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(subscription_status, 'blocked')
    from public.companies
    where id = public.current_company_id()
    limit 1
$$;

create or replace function public.current_company_subscription_active()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(
        case
            when subscription_status = 'active' then true
            when subscription_status = 'trial' then trial_ends_at is null or trial_ends_at >= now()
            else false
        end,
        false
    )
    from public.companies
    where id = public.current_company_id()
    limit 1
$$;

create or replace function public.current_company_monthly_project_count()
returns integer
language sql
stable
security definer
set search_path = public
as $$
    select count(*)::integer
    from public.projects
    where company_id = public.current_company_id()
      and created_at >= date_trunc('month', now())
      and created_at < date_trunc('month', now()) + interval '1 month'
$$;

