create table if not exists public.plans (
    slug text primary key,
    name text not null,
    description text not null default '',
    monthly_price numeric not null default 0,
    annual_price numeric not null default 0,
    max_users integer,
    max_projects_per_month integer,
    allow_financial boolean not null default false,
    allow_reports boolean not null default false,
    allow_team_sync boolean not null default true,
    active boolean not null default true,
    created_at timestamptz not null default now(),
